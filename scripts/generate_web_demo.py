from pathlib import Path
import math,subprocess,hashlib,json
root=Path(__file__).resolve().parents[1]; out=root/'web/public/demo';out.mkdir(parents=True,exist_ok=True)
w,h=720,480
base=Image.new('RGB',(w,h)); pix=base.load()
for y in range(h):
 t=y/h
 for x in range(w):
  glow=max(0,1-math.hypot((x-480)/530,(y-210)/350))
  pix[x,y]=(int(20+35*t+54*glow),int(27+35*t+42*glow),int(54+30*t+22*glow))
def frame(i):
 im=base.copy();d=ImageDraw.Draw(im); shift=math.sin(i/47*math.pi*2)*9
